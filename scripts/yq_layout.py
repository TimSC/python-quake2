"""
Write game/savegame/layout.py: the x86_64 memory layout of the structs that
Yamagi's savegame code writes with fwrite (edict_t, gclient_t,
level_locals_t, game_locals_t and the savegame header), so the port reads
and writes the same files as Yamagi's game.so.

usage: yq_layout.py

Needs gcc and pahole. The layout comes from compiling Yamagi's headers
with debug info; the generated module is checked in, so the game itself
needs neither.

See docs/yquake2_plan.md.
"""
from __future__ import annotations

import os
import re
import subprocess
import tempfile
import pprint

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "yquake2", "src", "game")
TOP = ["edict_s", "gclient_s", "level_locals_t", "game_locals_t", "savegameHeader_t"]

MEMBER_RE = re.compile(r"^\t(?P<type>[^(]+?)\s*(?P<name>\w+)(?P<dims>(?:\[\d+\])*);\s*/\*\s*(?P<off>\d+)\s+(?P<size>\d+)\s*\*/")
FPTR_RE = re.compile(r"^\t.*\(\*(?P<name>\w+)\)\(.*\);\s*/\*\s*(?P<off>\d+)\s+(?P<size>\d+)\s*\*/")
SIZE_RE = re.compile(r"/\* size: (\d+)")

PRIM = {("float", 4): "f", ("double", 8): "d", ("char", 1): "c", ("const char", 1): "c", ("short", 2): "h",
	("short int", 2): "h", ("unsigned short", 2): "H", ("short unsigned int", 2): "H", ("byte", 1): "B",
	("unsigned char", 1): "B", ("signed char", 1): "b", ("unsigned int", 4): "I", ("unsigned", 4): "I"}


def pahole(obj, name):
	r = subprocess.run(["pahole", "-C", name, obj], capture_output=True, text=True)
	return r.stdout


def main():
	tmp = tempfile.mkdtemp()
	src = os.path.join(tmp, "layout.c")
	open(src, "w").write('#include "header/local.h"\n#include "savegame/savegame.h"\n'
		"edict_t e; gclient_t c; level_locals_t l; game_locals_t g; savegameHeader_t h;\n")
	obj = os.path.join(tmp, "layout.o")
	subprocess.run(["gcc", "-g", "-c", "-I" + GAME, "-o", obj, src], check=True)
	layouts = {}
	todo = list(TOP)
	while todo:
		name = todo.pop(0)
		if name in layouts: continue
		text = pahole(obj, name)
		m = re.match(r"\s*typedef struct (\w+) \w+;\s*$", text)
		if m:	# a typedef of a struct tag
			text = pahole(obj, m.group(1))
		if not text.strip():
			raise SystemExit("pahole has no struct %s" % name)
		members = []
		for line in text.splitlines():
			m = FPTR_RE.match(line)
			if m:
				members.append((m.group("name"), int(m.group("off")), "ptr", 1, None)); continue
			m = MEMBER_RE.match(line)
			if not m: continue
			typ = re.sub(r"\s+", " ", m.group("type").strip())
			nm, off, size = m.group("name"), int(m.group("off")), int(m.group("size"))
			dims = [int(d) for d in re.findall(r"\[(\d+)\]", m.group("dims"))]
			count = 1
			for d in dims: count *= d
			if "*" in typ:
				members.append((nm, off, "ptr", count, None)); continue
			base = typ.replace("struct ", "")
			if base == "vec3_t":
				members.append((nm, off, "f", 3 * count, None)); continue
			elem = size // count
			kind = PRIM.get((base, elem))
			if kind is None and (base in ("int", "qboolean") or (elem == 4 and "/* size:" not in pahole(obj, base))):
				kind = "i"	# int, qboolean and enums
			if kind:
				members.append((nm, off, kind, count, None)); continue
			members.append((nm, off, "struct", count, base))
			todo.append(base)
		m = SIZE_RE.search(text)
		if not m: raise SystemExit("no size for %s:\n%s" % (name, text[:300]))
		size = int(m.group(1))
		layouts[name] = {"size": size, "members": members}
	out = os.path.join(ROOT, "game", "savegame", "layout.py")
	os.makedirs(os.path.dirname(out), exist_ok=True)
	open(out, "w").write('"""\nMemory layout (x86_64, gcc) of the structs Yamagi\'s savegame code\n'
		'writes with fwrite. Generated by scripts/yq_layout.py from Yamagi\'s headers\n'
		'(Q2PORT: C gets this from the compiler).\n\n'
		'Each struct: {"size": bytes, "members": [(name, offset, kind, count, struct name)]}.\n'
		'kind is a struct format letter (i, I, h, H, b, B, c, f, d), "ptr" or "struct".\n"""\n'
		"from __future__ import annotations\n\nLAYOUT = " + pprint.pformat(layouts, width=120) + "\n")
	for n in TOP: print(n, layouts[n]["size"])


if __name__ == "__main__":
	main()
