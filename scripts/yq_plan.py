"""
Generate a yq_move.py plan for one group of the yquake2 move from the symbol
map (scripts/yq_map.json, written by yq_index.py).

usage:
  yq_plan.py <out_plan.py> --modules a.py b.py ... --allow dir1 dir2 ... [--override sym=path.py ...]

--modules   the port's current Python files in the group
--allow     Python dirs (under the repo) the group may create files in; symbols whose
            Yamagi home is elsewhere stay with their module's main target for now
--override  force a symbol's target (e.g. "TO_SHORT=common/shared/shared.py")

See docs/yquake2_plan.md.
"""
from __future__ import annotations

import os
import sys
import json
import pprint
import collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import yq_index as yi


def main(argv):
	out = argv[0]
	mods, allow, over = [], [], {}
	mode = None
	for a in argv[1:]:
		if a in ("--modules", "--allow", "--override"): mode = a; continue
		if mode == "--modules": mods.append(a)
		elif mode == "--allow": allow.append(a.rstrip("/"))
		elif mode == "--override":
			k, v = a.split("="); over[k] = v
	data = json.load(open(os.path.join(yi.ROOT, "scripts", "yq_map.json")))["modules"]
	renames, splits = {}, {}
	report = []
	for m in mods:
		info = data[m]
		default = yi.yq_py_path(info["default"]) if info["default"] else None
		if default is None:
			report.append("NO TARGET: %s (add it by hand)" % m); continue
		# the header counterpart, if any symbol goes there
		targets = collections.Counter()
		sym_t = {}
		for e in info["symbols"]:
			if e["name"] in over:
				t = over[e["name"]]
			elif e["kind"] == "alias" or not e["yq"]:
				t = None
			else:
				t = yi.yq_py_path(e["yq"])
				if not any(t == d or t.startswith(d + "/") for d in allow):
					t = None	# its home belongs to a later group
			sym_t[e["name"]] = (t, e["kind"])
			if t: targets[t] += 1
		header = None
		for t in targets:
			if "/header/" in t or t.endswith("_h.py"):
				if header is None or targets[t] > targets[header]: header = t
		final = {}
		for name, (t, kind) in sym_t.items():
			if t is None:
				t = header if (kind in ("var", "class") and header) else default
			final[name] = t
		if len(set(final.values()) | {default}) == 1:
			renames[m] = default
		else:
			splits[m] = {"default": default, "symbols": {k: v for k, v in final.items() if v != default}}
		c = collections.Counter(final.values())
		report.append("%-22s -> %s" % (m, ", ".join("%s:%d" % kv for kv in c.most_common())))
	with open(out, "w") as f:
		f.write('"""yq_move.py plan, generated by yq_plan.py."""\n\n')
		f.write("RENAMES = " + pprint.pformat(renames, width=120) + "\n\n")
		f.write("SPLITS = " + pprint.pformat(splits, width=120) + "\n")
	print("\n".join(report))
	print("wrote", out)


if __name__ == "__main__":
	main(sys.argv[1:])
