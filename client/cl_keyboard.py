def Key_Unbind_f ():

	#int		b;

	if cmdparser.Cmd_Argc() != 2:
	
		clientserver.Com_Printf ("unbind <key> : remove commands from a key\n")
		return
	
	
	b = Key_StringToKeynum (cmdparser.Cmd_Argv(1))
	if b==-1:
	
		clientserver.Com_Printf ("\"{}\" isn't a valid key\n".format( cmdparser.Cmd_Argv(1)))
		return;
	

	Key_SetBinding (b, "")

