def CompleteCommand ():

	#char	*cmd, *s;
	global key_lines, edit_line

	s = key_lines[edit_line]
	if len(s) > 1:
		cursor = 1
		if s[cursor] == '\\' or s[cursor] == '/':
			cursor+=1
		s = s[cursor:]

	cmdStr = cmdparser.Cmd_CompleteCommand (s)
	if cmdStr is None:
		cmdStr = cvar.Cvar_CompleteVariable (s)
	if cmdStr is not None:
	
		line = ']/' + cmdStr + ' '
		key_lines[edit_line] = line

		return
	
