#define CL_SOUND_LOCAL_H

MAX_CHANNELS = 32
MAX_RAW_SAMPLES = 8192

"""
 * Holds one sample with 2 channels
"""
class portable_samplepair_t(object):

	def __init__(self):

		self.left = 0 #int
		self.right = 0 #int

"""
 * Holds a cached SFX and
 * it's meta data
"""
class sfxcache_t(object):

	def __init__(self):

		self.length = 0 #int
		self.loopstart = 0 #int
		self.speed = 0 #int
		self.width = 0 #int
		#if USE_OPENAL
		self.size = 0 #int
		self.bufnum = 0 #int
		#endif
		self.stereo = 0 #int

		# effect length
		# begin<->attack..fade<->end
		self.begin = 0 #int
		self.end = 0 #int
		self.attack = 0 #int
		self.fade = 0 #int

		# effect volume
		self.volume = 0 #short
		self.data = None #byte [1], variable sized

"""
 * Holds a SFX
"""
class sfx_t(object):

	def __init__(self):

		self.clear()

	def clear(self):

		# memset(sfx, 0, sizeof(*sfx))
		self.name = "" #char [MAX_QPATH]
		self.registration_sequence = 0 #int
		self.cache = None #sfxcache_t *
		self.truename = None #char *
		self.is_silenced_muzzle_flash = False #qboolean

	def __repr__(self):

		return "sfx_t ({})".format(self.name)

"""
 * A playsound_t will be generated by each call
 * to S_StartSound. When the mixer reaches
 * playsound->begin, the playsound will
 * be assigned to a channel.
"""
class playsound_t(object):

	def __init__(self):

		self.clear()

	def clear(self):

		# struct playsound_s *prev, *next; Q2PORT: the lists in sound.c
		self.sfx = None #sfx_t *
		self.volume = 0.0 #float
		self.attenuation = 0.0 #float
		self.entnum = 0 #int
		self.entchannel = 0 #int
		self.fixed_origin = False #qboolean
		self.origin = np.zeros((3,), dtype=np.float32) #vec3_t
		self.begin = 0 #unsigned

	def __repr__(self):

		return "playsound_t ({}, {})".format(self.sfx, self.begin)

"""
 * Interface to pass data and metadata
 * between the frontend and the backends.
 * Mainly used by the SDL backend, since
 * the OpenAL backend has it's own AL
 * based magic.
"""
class sound_t(object):

	def __init__(self):

		self.channels = 0 #int
		self.samples = 0 #int, mono samples in buffer
		self.submission_chunk = 0 #int, don't mix less than this
		self.samplepos = 0 #int, in mono samples
		self.samplebits = 0 #int
		self.speed = 0 #int
		self.buffer = None #unsigned char *

"""
 * Hold all information for one
 * playback channel.
"""
class channel_t(object):

	def __init__(self):

		self.clear()

	def clear(self):

		# memset(ch, 0, sizeof(*ch))
		self.sfx = None #sfx_t *, sfx number
		self.leftvol = 0 #int, 0-255 volume
		self.rightvol = 0 #int, 0-255 volume
		self.end = 0 #int, end time in global paintsamples
		self.pos = 0 #int, sample position in sfx
		self.looping = 0 #int, where to loop, -1 = no looping
		self.entnum = 0 #int, to allow overriding a specific sound
		self.entchannel = 0 #int
		self.origin = np.zeros((3,), dtype=np.float32) #vec3_t, only use if fixed_origin is set
		self.dist_mult = 0.0 #vec_t, distance multiplier (attenuation/clipK)
		self.master_vol = 0 #int, 0-255 master volume
		self.fixed_origin = False #qboolean, use origin instead of fetching entnum's origin
		self.autosound = False #qboolean, from an entity->sound, cleared each frame
		#if USE_OPENAL
		self.autoframe = 0 #int
		self.oal_vol = 0.0 #float
		self.srcnum = 0 #int
		#endif

"""
 * Information read from
 * wave file header.
"""
class wavinfo_t(object):

	def __init__(self):

		self.rate = 0 #int
		self.width = 0 #int
		self.channels = 0 #int
		self.loopstart = 0 #int
		self.samples = 0 #int
		self.dataofs = 0 #int, chunk starts this many bytes from file start

"""
 * Type of active sound backend
"""
class sndstarted_t(Enum):

	SS_NOT = 0 # soundsystem not started
	SS_SDL = 1 # soundsystem started, using SDL
	SS_OAL = 2 # soundsystem started, using OpenAL

SS_NOT = sndstarted_t.SS_NOT
SS_SDL = sndstarted_t.SS_SDL
SS_OAL = sndstarted_t.SS_OAL

